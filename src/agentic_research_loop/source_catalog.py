"""Generate the source lists in the docs from each bundle's `source.json`."""

from __future__ import annotations

import re
from pathlib import Path

from .source_bundles import PACKAGED_BUNDLES, Bundle, available_bundles, load_bundle
from .sources import Category

CATEGORY_TITLES: dict[Category, str] = {
    "work-context": "Work context",
    "warehouse": "Warehouses and databases",
    "product-analytics": "Product, web, and experiment data",
    "observability-revenue": "Observability and revenue",
}
START = "<!-- source-list:start (generated by scripts/generate_source_docs.py) -->"
END = "<!-- source-list:end -->"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)


def _bundles(repo_root: Path) -> list[Bundle]:
    return [load_bundle(repo_root, name) for name in available_bundles(repo_root)]


def _in_category(bundles: list[Bundle], category: Category) -> list[Bundle]:
    return [bundle for bundle in bundles if bundle.spec.category == category]


def render_summary(repo_root: Path) -> str:
    """One line per category, for the README and program.md."""
    bundles = _bundles(repo_root)
    return "\n".join(
        f"- {title}: "
        + ", ".join(
            bundle.spec.display_name for bundle in _in_category(bundles, category)
        )
        for category, title in CATEGORY_TITLES.items()
    )


def _catalog_entry(bundle: Bundle) -> str:
    control = bundle.spec.read_only_control
    notes = " ".join(bundle.spec.notes.split())
    denied = bundle.server.write_tools if bundle.server else []
    deny_line = (
        f" Denied write tools: {', '.join(f'`{tool}`' for tool in denied)}."
        if denied
        else ""
    )
    return (
        f"- **[{bundle.spec.display_name}]({bundle.name}/SETUP.md)** "
        f"(`{bundle.name}`, {bundle.spec.transport}; read-only: "
        f"{control.mechanism}, `{control.detail}`). {bundle.spec.plan_line}{deny_line} {notes}"
    )


def render_catalog(repo_root: Path) -> str:
    """Every source in full, for the bundles README."""
    bundles = _bundles(repo_root)
    sections = [
        f"### {title}\n\n"
        + "\n".join(
            _catalog_entry(bundle) for bundle in _in_category(bundles, category)
        )
        for category, title in CATEGORY_TITLES.items()
    ]
    return "\n\n".join(sections)


def _replace_block(text: str, body: str) -> str:
    if BLOCK.search(text) is None:
        raise ValueError(f"missing marker block {START}")
    return BLOCK.sub(lambda _: f"{START}\n{body}\n{END}", text)


def expected_documents(repo_root: Path) -> dict[Path, str]:
    """Return each generated document as it should read on disk."""
    renderers = {
        repo_root / "README.md": render_summary,
        repo_root / "program.md": render_summary,
        PACKAGED_BUNDLES / "README.md": render_catalog,
    }
    return {
        path: _replace_block(path.read_text(encoding="utf-8"), render(repo_root))
        for path, render in renderers.items()
    }
